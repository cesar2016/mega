/**
 * En nativo Tailwind no puede aplicar `color` sobre un SVG, así que NativeWind
 * mueve la propiedad `color` del estilo al prop `color` del icono (que Lucide
 * usa como `stroke`).
 */
const OPTIONS = {
  className: { target: "style", nativeStyleToProp: { color: true } },
} as const;

const wrap = (component: unknown) =>
  cssInterop(component as never, OPTIONS as never) as unknown as IconComponent;

